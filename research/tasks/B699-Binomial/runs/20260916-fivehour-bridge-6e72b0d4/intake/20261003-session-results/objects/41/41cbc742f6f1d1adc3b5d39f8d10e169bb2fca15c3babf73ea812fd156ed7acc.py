"""Small exact utilities; standard library only. All analytic assertions use rationals."""
from __future__ import annotations
from fractions import Fraction as F
from functools import lru_cache
import hashlib, math
NLOG=32

def series(z:F)->tuple[F,F]:
    if not 0<=z<1:raise ValueError('invalid atanh argument')
    lo=sum((2*z**(2*j+1)/(2*j+1) for j in range(NLOG)),F(0))
    return lo,lo+2*z**(2*NLOG+1)/((2*NLOG+1)*(1-z*z))
L2,U2=series(F(1,3))

@lru_cache(maxsize=None)
def logs(x:F|int)->tuple[F,F]:
    x=F(x)
    if x<=0:raise ValueError('log argument must be positive')
    k=0
    while x>=2:x/=2;k+=1
    while x<1:x*=2;k-=1
    l,u=series((x-1)/(x+1))
    return (l+k*L2,u+k*U2) if k>=0 else (l+k*U2,u+k*L2)

def scaled(l:F,u:F,scale:int=10**15)->dict:
    return {'scale':scale,'lower_floor':l.numerator*scale//l.denominator,
            'upper_ceil':-((-u.numerator*scale)//u.denominator)}

def linear_interval(const:F,coefs:dict[int,F])->tuple[F,F]:
    lo=hi=const
    for q,a in sorted(coefs.items()):
        l,u=logs(q)
        lo+=a*(l if a>=0 else u); hi+=a*(u if a>=0 else l)
    return lo,hi

def trial(n:int)->bool:
    if n<2:return False
    if n%2==0:return n==2
    return all(n%d for d in range(3,math.isqrt(n)+1,2))

def primes_sieve(n:int)->list[int]:
    a=bytearray(b'\x01')*(n+1)
    a[:2]=b'\x00\x00'
    for p in range(2,math.isqrt(n)+1):
        if a[p]:a[p*p::p]=b'\x00'*((n-p*p)//p+1)
    return [i for i in range(2,n+1) if a[i]]

def primes_segmented(n:int):
    # The base is generated by trial division, not the full-sieve implementation.
    base=[p for p in range(2,math.isqrt(n)+1) if trial(p)]
    step=65536
    for lo in range(2,n+1,step):
        hi=min(n,lo+step-1); marks=bytearray(b'\x01')*(hi-lo+1)
        for p in base:
            if p*p>hi:break
            start=max(p*p,((lo+p-1)//p)*p)
            if start<=hi:marks[start-lo::p]=b'\x00'*((hi-start)//p+1)
        for j,v in enumerate(marks):
            if v:yield lo+j

def iroot_floor(n:int,e:int)->int:
    if n<0 or e<1:raise ValueError('invalid root')
    if n<2 or e==1:return n
    if e==2:return math.isqrt(n)
    lo=0;hi=1<<((n.bit_length()+e-1)//e)
    while lo+1<hi:
        m=(lo+hi)//2
        if m**e<=n:lo=m
        else:hi=m
    return hi if hi**e<=n else lo

def root_upper(y:F,e:int,scale:int=2**40)->F:
    y=F(y)
    z=y.numerator*scale**e
    q=iroot_floor(z//y.denominator,e)
    if q**e*y.denominator<z:q+=1
    assert (q-1)**e*y.denominator<z<=q**e*y.denominator
    return F(q,scale)

def floor_log2(y:F)->int:
    y=F(y); b=y.numerator.bit_length()-y.denominator.bit_length()
    if b>=0:
        if y<2**b:b-=1
    elif y<F(1,2**(-b)):b-=1
    assert F(2)**b<=y<F(2)**(b+1)
    return b

def vp_choose(n:int,k:int,p:int)->int:
    if not 0<=k<=n or p<2:raise ValueError('invalid valuation input')
    q=p;out=0
    while q<=n:
        v=n//q-k//q-(n-k)//q
        assert v in (0,1)
        out+=v;q*=p
    return out
