#!/usr/bin/env python3
"""Offline R07 replay. Ancestor archives are byte-audited, never executed.
Archive/hash-receipt structure is adapted from the frozen R06 replay utility.
"""
from __future__ import annotations
import argparse, hashlib, io, json, subprocess, sys, tempfile, zipfile
from pathlib import Path, PurePosixPath

PARENT_SHA='7843b895254058235150d91ec2ed6f5fdcd929fe9fb7cdcfcb3f32e0a58de9e9'
EXCLUDE_PAYLOAD={'MEMBERS.json','SHA256SUMS.txt','logs/CLEAN_REPLAY_RECEIPT.json'}

def need(ok,msg):
    if not ok:raise ValueError(msg)

def sha(data):return hashlib.sha256(data).hexdigest()
def canon(x):return (json.dumps(x,ensure_ascii=False,sort_keys=True,indent=2)+'\n').encode()

def safe(name):
    p=PurePosixPath(name)
    need(not p.is_absolute() and '..' not in p.parts and '\\' not in name,'unsafe archive/member path')

def audit_archive(data,chain='D-R06'):
    out=[]
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        names=[n.filename for n in z.infolist() if not n.is_dir()]
        need(len(names)==len(set(names)),'duplicate parent archive members')
        for n in names:safe(n)
        need(z.testzip() is None,'parent CRC failure')
        manifests=[n for n in names if n.endswith('/SHA256SUMS.txt') or n=='SHA256SUMS.txt']
        need(len(manifests)==1,'parent SHA manifest ambiguity')
        prefix=manifests[0][:-len('SHA256SUMS.txt')]
        for line in z.read(manifests[0]).decode().splitlines():
            if not line.strip():continue
            digest,n=line.split('  ',1);safe(n)
            need(prefix+n in names and sha(z.read(prefix+n))==digest.lower(),'parent declared hash failure')
        for n in sorted(names):
            b=z.read(n);out.append({'archive_chain':chain,'member':n,'size':len(b),'sha256':sha(b)})
            if n.lower().endswith('.zip'):out.extend(audit_archive(b,chain+'!'+n))
    return out

def audit_tree(root):
    need(all(not p.is_symlink() for p in root.rglob('*')),'symlink not allowed')
    files={p.relative_to(root).as_posix():p for p in root.rglob('*') if p.is_file()}
    checks={}
    for line in (root/'SHA256SUMS.txt').read_text().splitlines():
        if not line.strip():continue
        h,n=line.split('  ',1);safe(n);need(n not in checks,'duplicate SHA entry');checks[n]=h
    need(set(checks)==set(files)-{'SHA256SUMS.txt'},'SHA exact member coverage')
    for n,h in checks.items():need(sha(files[n].read_bytes())==h,'member hash failure: '+n)
    members=json.loads((root/'MEMBERS.json').read_text())
    need({r['path'] for r in members['members']}==set(files)-{'MEMBERS.json','SHA256SUMS.txt'},'MEMBERS exact coverage')
    for r in members['members']:
        b=files[r['path']].read_bytes();need(r['sha256']==sha(b) and r['size']==len(b),'MEMBERS hash/size failure')
        need(bool(r['source_ids']) and bool(r['origin_note']),'missing member provenance')
    payload=[{'path':n,'sha256':sha(p.read_bytes()),'size':p.stat().st_size} for n,p in sorted(files.items()) if n not in EXCLUDE_PAYLOAD]
    return files,members,sha(canon(payload))

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--output',required=True);args=ap.parse_args()
    root=Path(__file__).resolve().parent;out=Path(args.output).resolve()
    need(root not in out.parents,'replay output must be outside the package tree')
    files,members,payload=audit_tree(root)
    parent=(root/'dependencies/D-R06-evidence.zip').read_bytes();need(sha(parent)==PARENT_SHA,'wrong frozen parent')
    rows=audit_archive(parent);need(rows==members['recursive_parent_members'],'recursive provenance mismatch')
    with tempfile.TemporaryDirectory(prefix='b699-r07-exact-') as td:
        tmp=Path(td);cert=tmp/'certificate.json';receipt=tmp/'VERIFY.json'
        commands=[
          [sys.executable,'-I','-B',str(root/'scripts/build_certificate.py'),'--output',str(cert)],
          [sys.executable,'-I','-B',str(root/'scripts/verify_certificate.py'),'--certificate',str(cert),'--output',str(receipt),'--negative-tests']]
        statuses=[]
        for cmd in commands:
            run=subprocess.run(cmd,capture_output=True,text=True,timeout=120)
            need(run.returncode==0,'finite replay failure: '+run.stdout+run.stderr)
            statuses.append(json.loads(run.stdout.strip().splitlines()[-1]))
        need(cert.read_bytes()==(root/'certificates/certificate.json').read_bytes(),'certificate regenerated bytes differ')
        need(receipt.read_bytes()==(root/'logs/VERIFY.json').read_bytes(),'receiver regenerated bytes differ')
        finite=json.loads(receipt.read_text())
    result={'schema':'B699-D-R07-clean-replay-v1','status':'PASS','payload_sha256':payload,
      'package_member_count':len(files),'member_hashes_checked':len(files)-1,
      'parent_zip_sha256':PARENT_SHA,'recursive_parent_members_checked':len(rows),
      'certificate_sha256':sha((root/'certificates/certificate.json').read_bytes()),
      'regenerated_certificate_byte_identical':True,'regenerated_receiver_receipt_byte_identical':True,
      'finite_verification':finite,'subprocess_results':statuses,
      'ancestor_mathematics_executed_by_this_replay':False,'q6_terminal_executed':False,
      'external_BL_proof_verified':False,'new_uniform_proof_uses_BL':False,'paper_uniform_proof_formalized':False,'Lean_executed':False,'repository_actions':False}
    out.parent.mkdir(parents=True,exist_ok=True);out.write_bytes(canon(result))
    print(json.dumps({'status':'PASS','members':len(files),'parent_members':len(rows),
                      'negative_tests_rejected':len(finite['negative_tests']),'q6_executed':False}))
if __name__=='__main__':main()
