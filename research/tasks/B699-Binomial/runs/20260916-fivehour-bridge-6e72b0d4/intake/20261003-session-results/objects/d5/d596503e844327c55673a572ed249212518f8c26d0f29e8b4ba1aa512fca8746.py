#!/usr/bin/env python3
"""Offline exact R11 replay. Archive audit structure adapted from frozen R10.
No ancestor mathematics, network, repository writes, Lean, or q=6 terminal.
"""
from __future__ import annotations
import argparse,hashlib,io,json,subprocess,sys,tempfile,zipfile
from pathlib import Path,PurePosixPath
PARENT_SHA='69791706c40f3753e359765e464f38895060e6095ef35525931f553d9da6673a'
EXCLUDE_PAYLOAD={'MEMBERS.json','SHA256SUMS.txt','logs/CLEAN_REPLAY_RECEIPT.json'}
def need(ok,msg):
    if not ok:raise ValueError(msg)
def sha(b):return hashlib.sha256(b).hexdigest()
def canon(o):return (json.dumps(o,ensure_ascii=False,sort_keys=True,indent=2)+'\n').encode()
def safe(n):
    p=PurePosixPath(n)
    need(not p.is_absolute() and '..' not in p.parts and '\\' not in n,'unsafe member')
def audit_archive(data,chain='D-R10'):
    out=[]
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        names=[a.filename for a in z.infolist() if not a.is_dir()]
        need(len(names)==len(set(names)),'duplicate archive name')
        for n in names:safe(n)
        need(z.testzip() is None,'CRC failure')
        sums=[n for n in names if n=='SHA256SUMS.txt' or n.endswith('/SHA256SUMS.txt')]
        need(len(sums)==1,'parent SHA manifest ambiguity');prefix=sums[0][:-len('SHA256SUMS.txt')]
        for line in z.read(sums[0]).decode().splitlines():
            if not line.strip():continue
            h,n=line.split('  ',1);safe(n)
            need(prefix+n in names and sha(z.read(prefix+n))==h.lower(),'parent member hash failure')
        for n in sorted(names):
            b=z.read(n);out.append({'archive_chain':chain,'member':n,'size':len(b),'sha256':sha(b)})
            if n.lower().endswith('.zip'):out.extend(audit_archive(b,chain+'!'+n))
    return out

def audit_tree(root):
    need(all(not p.is_symlink() for p in root.rglob('*')),'symlink forbidden')
    files={p.relative_to(root).as_posix():p for p in root.rglob('*') if p.is_file()}
    sums={}
    for line in (root/'SHA256SUMS.txt').read_text().splitlines():
        if not line.strip():continue
        h,n=line.split('  ',1);safe(n);need(n not in sums,'duplicate manifest name');sums[n]=h
    need(set(sums)==set(files)-{'SHA256SUMS.txt'},'exact SHA file coverage')
    for n,h in sums.items():need(sha(files[n].read_bytes())==h,'member hash: '+n)
    m=json.loads((root/'MEMBERS.json').read_text())
    need({x['path'] for x in m['members']}==set(files)-{'MEMBERS.json','SHA256SUMS.txt'},'source-map coverage')
    for x in m['members']:
        b=files[x['path']].read_bytes()
        need(sha(b)==x['sha256'] and len(b)==x['size'] and x['source_ids'] and x['origin_note'],'member provenance/hash')
    payload=[{'path':n,'size':p.stat().st_size,'sha256':sha(p.read_bytes())}
             for n,p in sorted(files.items()) if n not in EXCLUDE_PAYLOAD]
    return files,m,sha(canon(payload))

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--output',required=True);a=ap.parse_args()
    root=Path(__file__).resolve().parent;output=Path(a.output).resolve()
    need(root not in output.parents,'write receipt outside the package')
    files,m,payload=audit_tree(root)
    b=(root/'dependencies/D-R10-evidence.zip').read_bytes();need(sha(b)==PARENT_SHA,'frozen parent mismatch')
    rows=audit_archive(b);need(rows==m['recursive_parent_members'],'recursive member source map')
    statuses=[]
    with tempfile.TemporaryDirectory(prefix='b699-r11-finite-') as td:
        t=Path(td);cert=t/'certificate.json';verify=t/'verify.json';demo=t/'demo.json';old=t/'old.json'
        commands=[
          [sys.executable,'-I','-B',str(root/'scripts/build_certificate.py'),'--output',str(cert)],
          [sys.executable,'-I','-B',str(root/'scripts/verify_certificate.py'),'--certificate',str(cert),'--output',str(verify),'--negative-tests'],
          [sys.executable,'-I','-B',str(root/'scripts/recover_exact.py'),'--n',str(3*(1<<402)),'--Q','19','--output',str(demo)],
          [sys.executable,'-I','-B',str(root/'scripts/recover_exact.py'),'--n','5342','--Q','3','--relaxed','--output',str(old)]]
        for cmd in commands:
            p=subprocess.run(cmd,capture_output=True,text=True,timeout=90)
            need(p.returncode==0,'finite command failed: '+p.stdout+p.stderr)
            statuses.append(json.loads(p.stdout.strip().splitlines()[-1]))
        for fresh,frozen in [(cert,'certificates/certificate.json'),(verify,'logs/VERIFY.json'),
                            (demo,'logs/NECESSARY_REJECTION_DEMO.json'),(old,'logs/RELAXED_REGRESSION.json')]:
            need(fresh.read_bytes()==(root/frozen).read_bytes(),'finite regenerated bytes differ: '+frozen)
        finite=json.loads(verify.read_text())
    result={'schema':'B699-D-R11-clean-replay-v1','status':'PASS','payload_sha256':payload,
      'package_member_count':len(files),'member_hashes_checked':len(files)-1,
      'parent_zip_sha256':PARENT_SHA,'recursive_parent_members_checked':len(rows),
      'certificate_sha256':sha((root/'certificates/certificate.json').read_bytes()),
      'certificate_regenerated_byte_identical':True,'verifier_receipt_regenerated_byte_identical':True,
      'both_recovery_demos_regenerated_byte_identical':True,'finite_verification':finite,
      'subprocess_results':statuses,'parent_mathematics_executed_by_this_replay':False,
      'parent_R10_own_local_run_separately_recorded':True,'q6_terminal_executed':False,
      'external_BL_proof_verified':False,'new_uniform_proof_uses_BL':False,
      'paper_proof_formalized':False,'Lean_executed':False,'repository_actions':False,
      'actual_NC3_count_computed':False,'new_certified_unbounded_original_domains':0}
    output.parent.mkdir(parents=True,exist_ok=True);output.write_bytes(canon(result))
    print(json.dumps({'status':'PASS','members':len(files),'parent_members':len(rows),
                      'negative_tests_rejected':len(finite['negative_tests']),'q6_executed':False}))
if __name__=='__main__':main()
