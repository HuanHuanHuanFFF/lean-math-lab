#!/usr/bin/env python3
"""Create member-level provenance and SHA256 manifest for this evidence tree.
No downloads, no repository commands. Excludes its two metadata outputs from
MEMBERS payload hashing; SHA256SUMS then covers MEMBERS and every other file.
"""
import argparse
import hashlib
import json
from pathlib import Path


def digest(p): return hashlib.sha256(p.read_bytes()).hexdigest()


def provenance(rel):
    if rel.startswith('sources/'):
        refs={'sources/OVERVIEW_relevant_excerpts.md':['S1'],
              'sources/D13_PROOFS_core_excerpt.md':['S2'],
              'sources/D13_HANDOFF_frontier_excerpt.md':['S3']}
        return {'origin':'connector text excerpt, not original raw file',
                'source_refs':refs.get(rel,[]),'producer':'session source transcription with explicit boundaries'}
    if rel.startswith('certificates/'):
        return {'origin':'new exact finite-ring computation','source_refs':['S2'],
                'producer':'scripts/build_certificate.py; checked by scripts/verify_certificate.py'}
    if rel=='logs/SECOND_FORMULA_VERIFY.json':
        return {'origin':'new same-session second-formula check','source_refs':['S2'],
                'producer':'scripts/verify_certificate.py --negative-tests'}
    if rel=='logs/CLEAN_REPLAY_RECEIPT.json':
        return {'origin':'clean extraction replay of this evidence payload',
                'source_refs':[],'producer':'replay.py, clean temporary extracted tree'}
    if rel.endswith('.py'):
        return {'origin':'new session author code','source_refs':['S2'],
                'producer':'D04 session; standard-library implementation'}
    return {'origin':'new session report/source ledger/state/log','source_refs':['S1','S2','S3','S4'],
            'producer':'D04 session'}


def main():
    ap=argparse.ArgumentParser();ap.add_argument('--root',type=Path,required=True);args=ap.parse_args()
    root=args.root.resolve()
    payload=[]
    for p in sorted(root.rglob('*')):
        if p.is_symlink(): raise RuntimeError('Symlinks are not permitted')
        if not p.is_file(): continue
        rel=p.relative_to(root).as_posix()
        if rel in ('MEMBERS.json','SHA256SUMS.txt'): continue
        payload.append({'path':rel,'bytes':p.stat().st_size,'sha256':digest(p),**provenance(rel)})
    obj={'schema':'B699-D04-member-provenance-v1','payload_members':payload,
         'metadata_exclusions':{
             'MEMBERS.json':{'origin':'generated by scripts/package_manifest.py',
                             'hash_binding':'SHA256SUMS.txt'},
             'SHA256SUMS.txt':{'origin':'generated by scripts/package_manifest.py',
                               'hash_binding':'external final ZIP SHA256'}},
         'hash_algorithm':'SHA-256','source_original_bytes_not_available':'See SOURCE_ADOPTION.md; excerpt hashes are not original source hashes'}
    (root/'MEMBERS.json').write_text(json.dumps(obj,ensure_ascii=False,sort_keys=True,indent=2)+'\n',encoding='utf-8')
    lines=[]
    for p in sorted(root.rglob('*')):
        if p.is_file() and p.name!='SHA256SUMS.txt':
            lines.append(digest(p)+'  '+p.relative_to(root).as_posix())
    (root/'SHA256SUMS.txt').write_text('\n'.join(lines)+'\n',encoding='utf-8')
    print(json.dumps({'payload_members':len(payload),'hash_manifest_members':len(lines)},sort_keys=True))

if __name__=='__main__': main()
