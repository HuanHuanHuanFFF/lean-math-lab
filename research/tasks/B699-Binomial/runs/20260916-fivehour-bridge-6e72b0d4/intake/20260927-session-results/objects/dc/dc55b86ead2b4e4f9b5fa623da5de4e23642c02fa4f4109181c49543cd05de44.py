"""Offline, read-only replay of this round. Python standard library only."""
import sys,os,hashlib,tempfile,subprocess
from pathlib import Path
sys.dont_write_bytecode=True
ROOT=Path(__file__).resolve().parent

def main():
 manifest=ROOT/'SHA256SUMS.txt'
 if not manifest.exists():manifest=ROOT/'PAYLOAD_SHA256SUMS.txt'
 if not manifest.exists():raise RuntimeError('Missing manifest')
 count=0
 for line in manifest.read_text().splitlines():
  digest,name=line.split(maxsplit=1);path=(ROOT/name.removeprefix('./')).resolve()
  if not path.is_relative_to(ROOT):raise RuntimeError('Unsafe path')
  if hashlib.sha256(path.read_bytes()).hexdigest()!=digest:raise RuntimeError('Digest mismatch: '+name)
  count+=1
 print('HASH PASS:',count,manifest.name,flush=True)
 env=dict(os.environ,PYTHONDONTWRITEBYTECODE='1')
 subprocess.run([sys.executable,str(ROOT/'evidence/verify.py')],cwd=ROOT,env=env,check=True)
 with tempfile.TemporaryDirectory(prefix='a1486-regenerate-') as t:
  out=Path(t)
  subprocess.run([sys.executable,str(ROOT/'evidence/generate.py'),'--out',str(out)],cwd=ROOT,env=env,check=True)
  original=sorted(p.name for p in (ROOT/'certificates').glob('*.json'))
  if original!=sorted(p.name for p in out.glob('*.json')):raise RuntimeError('Certificate file set differs')
  for name in original:
   if (out/name).read_bytes()!=(ROOT/'certificates'/name).read_bytes():raise RuntimeError('Regenerated bytes differ: '+name)
  print('BYTE REGENERATION PASS:',len(original),'certificates',flush=True)
 print('CLEAN REPLAY PASS: no package files modified',flush=True)
if __name__=='__main__':main()
