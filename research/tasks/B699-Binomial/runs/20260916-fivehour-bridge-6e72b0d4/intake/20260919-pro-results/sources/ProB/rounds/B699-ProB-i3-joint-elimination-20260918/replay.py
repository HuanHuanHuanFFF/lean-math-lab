#!/usr/bin/env python3
"""Verify member hashes, rebuild exact outputs, compare frozen bytes."""
from __future__ import annotations
import hashlib
from pathlib import Path
import subprocess
import sys

ROOT=Path(__file__).resolve().parent

def digest(path:Path)->str:
    return hashlib.sha256(path.read_bytes()).hexdigest()

def main()->int:
    try:
        import sympy
    except ImportError:
        print('Missing SymPy: run python -m pip install -r requirements.txt',file=sys.stderr)
        return 2
    if sympy.__version__!='1.14.0':
        print('This frozen replay requires SymPy 1.14.0; use requirements.txt.',file=sys.stderr)
        return 2
    manifest=ROOT/'SHA256SUMS'
    if not manifest.exists():
        print('Missing SHA256SUMS. This is not a complete evidence package.',file=sys.stderr)
        return 2
    entries={}
    for line in manifest.read_text().splitlines():
        if not line:continue
        sha,name=line.split('  ',1)
        p=ROOT/name
        if not p.resolve().is_relative_to(ROOT):raise ValueError('Unsafe manifest path')
        entries[name]=sha
    for name,sha in entries.items():
        if digest(ROOT/name)!=sha:raise AssertionError(f'Pre-run hash mismatch: {name}')
    print(f'MANIFEST_BEFORE: {len(entries)} members verified',flush=True)
    for script in ['symbolic_checks.py','local_boundary.py']:
        subprocess.run([sys.executable,str(ROOT/'code'/script)],cwd=ROOT,check=True)
    for name,sha in entries.items():
        if digest(ROOT/name)!=sha:raise AssertionError(f'Post-run/frozen-output hash mismatch: {name}')
    print('FROZEN_OUTPUTS: regenerated bytes match SHA256SUMS',flush=True)
    print('SCOPE: paper identities and local-method boundary; NO new NC3 closure, NO Lean.',flush=True)
    return 0

if __name__=='__main__':
    try: raise SystemExit(main())
    except (AssertionError,ValueError,OSError,subprocess.CalledProcessError) as exc:
        print(f'REPLAY FAILED: {exc}',file=sys.stderr)
        raise SystemExit(1)
