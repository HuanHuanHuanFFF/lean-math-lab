#!/usr/bin/env python3
"""Verify a frozen payload, regenerate all certificates, and run a separate verifier.
Writes only to temporary directories and the explicitly supplied receipt path.
"""
from pathlib import Path
import argparse,hashlib,json,os,platform,subprocess,sys,tempfile,time

CERTS=['rows.json','endpoint.json','witnesses.json','regression.json']

def digest(p):return hashlib.sha256(p.read_bytes()).hexdigest()

def manifest(root,name):
    p=root/name
    if not p.is_file():return None
    records=[]
    for line in p.read_text(encoding='utf-8').splitlines():
        if not line.strip():continue
        wanted,relative=line.split('  ',1)
        path=(root/relative).resolve()
        if root.resolve() not in path.parents:raise ValueError('manifest path escape')
        got=digest(path)
        if got!=wanted:raise ValueError('SHA256 mismatch: '+relative)
        records.append(relative)
    return dict(file=name,status='PASS',verified_files=len(records))

def main():
    ap=argparse.ArgumentParser();ap.add_argument('--receipt',required=True);arg=ap.parse_args()
    root=Path(__file__).resolve().parents[1];receipt=Path(arg.receipt).resolve()
    if receipt==root or root in receipt.parents:raise ValueError('receipt must be outside frozen input root')
    start=time.time()
    manifests=[manifest(root,'SHA256SUMS.payload'),manifest(root,'SHA256SUMS.txt')]
    if manifests[0] is None:raise ValueError('payload manifest missing')
    commands=[]
    with tempfile.TemporaryDirectory(prefix='b699-c-r12-replay-') as tmp:
        tmp=Path(tmp);gen=tmp/'discovery';acc=tmp/'acceptance'
        env=dict(os.environ,PYTHONDONTWRITEBYTECODE='1',PYTHONHASHSEED='0')
        specs=[['scripts/discover.py','--out',str(gen)],
               ['scripts/accept.py','--cert-dir',str(root/'certificates'),'--out',str(acc)]]
        for spec in specs:
            cmd=[sys.executable,str(root/spec[0]),*spec[1:]]
            step=time.time()
            proc=subprocess.run(cmd,cwd=root,env=env,text=True,capture_output=True)
            info=dict(script=spec[0],returncode=proc.returncode,stdout=proc.stdout,stderr=proc.stderr,seconds=round(time.time()-step,6))
            commands.append(info)
            print(proc.stdout,end='',flush=True)
            if proc.stderr:print(proc.stderr,file=sys.stderr,end='',flush=True)
            if proc.returncode:raise RuntimeError('replay subprocess failed: '+spec[0])
        hashes={}
        for name in CERTS:
            original=(root/'certificates'/name).read_bytes()
            if original!=(gen/name).read_bytes() or original!=(acc/name).read_bytes():
                raise ValueError('regenerated bytes disagree: '+name)
            hashes[name]=hashlib.sha256(original).hexdigest()
        summary=json.loads(commands[-1]['stdout'].splitlines()[-1])
        if summary['status']!='PASS' or summary['mutation_rejections']!=10:raise ValueError('acceptance summary invalid')
    data=dict(status='PASS',round='C Round 12',input_root=str(root),python=platform.python_version(),
              manifest_checks=[x for x in manifests if x is not None],
              certificate_count=len(CERTS),certificates_sha256=hashes,
              discovery_and_separate_acceptance_byte_equal=True,mutation_rejections=10,
              endpoint_counts=summary['endpoint_counts'],commands=commands,
              seconds=round(time.time()-start,6),
              interpretation='Deterministic same-author replay, not Lean or external independent mathematical review.')
    receipt.parent.mkdir(parents=True,exist_ok=True)
    receipt.write_text(json.dumps(data,ensure_ascii=False,sort_keys=True,indent=2)+'\n',encoding='utf-8')
    print('REPLAY PASS:',receipt,flush=True)
if __name__=='__main__':main()
