#!/usr/bin/env python3
"""Replay into a new directory; never overwrite the frozen package."""
from __future__ import annotations
import sys
sys.dont_write_bytecode=True
import argparse,copy,hashlib,json,platform,subprocess
from pathlib import Path
import check_a,check_b

ROOT=Path(__file__).resolve().parents[1]

def negative_cases(base):
    cases=[]
    def add(name,mut):
        obj=copy.deepcopy(base);mut(obj);cases.append((name,obj))
    add('forbid_allowed_prime_3',lambda d:d['scope'].__setitem__('allow_prime_3',False))
    add('reverse_necessary_implication',lambda d:d['scope'].__setitem__('polynomial_divisibility_is_not_sufficient',False))
    add('silently_drop_NC4_dependency',lambda d:d['scope'].__setitem__('adopted_NC3_implies_4_divides_n',False))
    add('claim_all_quartics',lambda d:d['statements'].__setitem__('cubic_degree',4))
    add('weaken_primary_strict_bound',lambda d:d['statements'].__setitem__('primary_comparison','3e_ge_2d'))
    add('weaken_split_strict_gap',lambda d:d['statements'].__setitem__('split_comparison','h_ge_2r'))
    add('changed_polynomial_identity',lambda d:d['identities'][0].__setitem__('lhs',['add',d['identities'][0]['lhs'],1]))
    add('detached_mod3_unit',lambda d:d['unit_mod3']['polynomial'].__setitem__(0,d['unit_mod3']['polynomial'][0]+3))
    add('changed_pseudo_remainder',lambda d:d['pseudo_divisions'][0]['pseudo_remainder'].__setitem__(0,1))
    add('truncate_actual_source_power',lambda d:d['rows'][2].__setitem__('source_exponent',d['rows'][2]['source_exponent']-1))
    add('composite_working_prime',lambda d:d['rows'][0].__setitem__('p',9))
    add('too_small_working_base',lambda d:d['rows'][0].__setitem__('e',1))
    add('dyadic_instead_of_odd_source',lambda d:d['rows'][0].__setitem__('p',2))
    split_i=next(i for i,r in enumerate(base['rows']) if r['kind']=='split')
    add('actual_split_equality_case',lambda d:d['rows'][split_i].__setitem__('h',2*(len(d['rows'][split_i]['U'])-1)))
    add('non_Eisenstein_B',lambda d:d['rows'][split_i].__setitem__('B',4))
    add('missing_one_original_carry',lambda d:d['exception_samples'][0].__setitem__('carries',[1,1,0]))
    add('changed_original_input',lambda d:d['exception_samples'][0].__setitem__('tau',str(int(d['exception_samples'][0]['tau'])+1)))
    add('missing_identity',lambda d:d['identities'].pop())
    return cases

def main():
    p=argparse.ArgumentParser();p.add_argument('--output-dir',type=Path,required=True);p.add_argument('--regenerate',action='store_true');a=p.parse_args()
    a.output_dir.mkdir(parents=True,exist_ok=False)
    cert=ROOT/'certificates'/'round6.json';base=json.loads(cert.read_text())
    result={'certificate_sha256':hashlib.sha256(cert.read_bytes()).hexdigest(), 'python':platform.python_version(),
            'A':check_a.check(base),'B':check_b.check(base),'negative_tests':[]}
    for name,changed in negative_cases(base):
        rec={'name':name}
        for tag,module in [('A',check_a),('B',check_b)]:
            try:module.check(changed)
            except (ValueError,KeyError,TypeError,IndexError) as e:rec[tag]={'status':'REJECT','reason':str(e)}
            else:raise RuntimeError(f'{tag} accepted bad certificate: {name}')
        result['negative_tests'].append(rec)
    if a.regenerate:
        other=a.output_dir/'regenerated.json'
        proc=subprocess.run([sys.executable,str(ROOT/'src'/'generate.py'),'--out',str(other)],capture_output=True,text=True,check=True)
        (a.output_dir/'regeneration.log').write_text(proc.stdout+proc.stderr)
        if other.read_bytes()!=cert.read_bytes():raise RuntimeError('regenerated bytes differ')
        result['regeneration']={'status':'BYTE_IDENTICAL','sha256':hashlib.sha256(other.read_bytes()).hexdigest()}
    result['status']='PASS'
    (a.output_dir/'replay.json').write_text(json.dumps(result,ensure_ascii=False,sort_keys=True,indent=2)+'\n')
    print(json.dumps({'status':'PASS','A':result['A'],'B':result['B'],'negative_tests_rejected_by_both':len(result['negative_tests']),
                      'regenerated':bool(a.regenerate)},ensure_ascii=False))

if __name__=='__main__':main()
