#!/usr/bin/env python3
"""Read-only round-8 replay. All new outputs go to a fresh requested directory."""
import sys,os,json,copy,hashlib,argparse,subprocess,time
from pathlib import Path
sys.dont_write_bytecode=True
from check_a import check as check_a
from check_b import check as check_b

def setpath(d,path,value):
    for p in path[:-1]:d=d[p]
    d[path[-1]]=value

def bump(d,path):
    for p in path[:-1]:d=d[p]
    d[path[-1]]+=1

def mutations():
    return [
      ('scope_full_quintic',lambda d:setpath(d,['claim'],'QUINTIC-ALL')),
      ('lower_gate',lambda d:setpath(d,['threshold_power'],12)),
      ('missing_generic_slot',lambda d:d['generic'].pop()),
      ('wrong_generic_quotient',lambda d:bump(d,['generic',0,'Q',0,1,0])),
      ('repeated_inverse_erased',lambda d:setpath(d,['cases',0,'inv_r'],[[0,1]])),
      ('squarefree_inverse_forged',lambda d:setpath(d,['cases',3,'inv_r'],[[1,1]])),
      ('wrong_ell',lambda d:bump(d,['cases',1,'ell',0])),
      ('wrong_origin_shift',lambda d:bump(d,['cases',3,'shift',1,0])),
      ('wrong_factor',lambda d:bump(d,['cases',4,'factors',1,'p',0,0])),
      ('missing_case',lambda d:d['cases'].pop()),
      ('wrong_F5',lambda d:bump(d,['canonical','N',1,0])),
      ('wrong_Bezout',lambda d:bump(d,['canonical','bezout_A',0,0])),
      ('wrong_3125_identity',lambda d:bump(d,['canonical','mod3125_quotient',1,0])),
      ('wrong_H_recovery',lambda d:bump(d,['canonical','recovery','H',0,0])),
      ('wrong_u_recovery',lambda d:bump(d,['canonical','recovery','u',0,0])),
      ('wrong_root_target',lambda d:bump(d,['root_exclusions',2,'target'])),
      ('wrong_Frobenius',lambda d:bump(d,['root_exclusions',2,'frob',0])),
      ('wrong_field_Bezout',lambda d:bump(d,['root_exclusions',2,'bezout_A',0])),
      ('wrong_power2_log',lambda d:setpath(d,['exponent','power2_residue'],1)),
      ('missing_exponent_class',lambda d:d['exponent']['classes'].pop()),
      ('fake_gcd',lambda d:setpath(d,['weak_example','g'],8)),
      ('fake_actual_Psi',lambda d:bump(d,['weak_example','Psi',0])),
      ('fake_witness',lambda d:bump(d,['weak_example','witnesses',0,'v_nj'])),
      ('nonprime_work_base',lambda d:setpath(d,['applications',0,'p'],9)),
      ('below_gate',lambda d:setpath(d,['applications',0,'e'],1)),
      ('truncated_source',lambda d:setpath(d,['applications',3,'source_E'],106)),
      ('negative_coefficient_parameter',lambda d:setpath(d,['applications',0,'b'],-1)),
      ('wrong_mirror_value',lambda d:setpath(d,['canonical','mirror'],[3,32])),
      ('wrong_mirror_exponent',lambda d:bump(d,['mirror_examples',0,'exponent'])),
    ]

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--output-dir',required=True)
    parser.add_argument('--regenerate',action='store_true');parser.add_argument('--skip-negative',action='store_true')
    parser.add_argument('--negative-start',type=int,default=0);parser.add_argument('--negative-stop',type=int,default=None)
    args=parser.parse_args();root=Path(__file__).resolve().parents[1]
    out=Path(args.output_dir).resolve()
    if out.exists():raise SystemExit('Refusing to overwrite existing output directory')
    out.mkdir(parents=True)
    raw=(root/'certificates/round8.json').read_bytes();data=json.loads(raw)
    started=time.monotonic()
    report={'schema':'B699-R8-replay-v1','certificate_sha256':hashlib.sha256(raw).hexdigest(),
            'python':sys.version.split()[0],'checker_A':check_a(data),'checker_B':check_b(data),'negative_tests':[]}
    if not args.skip_negative:
        tests=mutations()[args.negative_start:args.negative_stop]
        for name,mutate in tests:
            bad=copy.deepcopy(data);mutate(bad);errors={}
            for label,checker in [('A',check_a),('B',check_b)]:
                try:checker(bad)
                except Exception as exc:errors[label]=str(exc)
            ok=len(errors)==2
            report['negative_tests'].append({'name':name,'both_rejected':ok,'errors':errors})
            if not ok:raise ValueError('bad certificate not rejected by both: '+name)
        print('NEGATIVES',len(tests),'PASS',flush=True)
    report['regenerated']=False
    if args.regenerate:
        target=out/'regenerated.json'
        cp=subprocess.run([sys.executable,str(root/'src/generate.py'),'--output',str(target)],capture_output=True,text=True)
        (out/'regenerate.log').write_text(cp.stdout+cp.stderr)
        if cp.returncode:raise RuntimeError('regeneration failed')
        if target.read_bytes()!=raw:raise ValueError('regenerated bytes differ')
        report['regenerated']=True
    report['status']='PASS';report['elapsed_seconds']=round(time.monotonic()-started,3)
    (out/'report.json').write_text(json.dumps(report,ensure_ascii=False,indent=2,sort_keys=True)+'\n')
    print(json.dumps({'status':'PASS','negative_count':len(report['negative_tests']),'regenerated':report['regenerated'],'output':str(out)},sort_keys=True))
if __name__=='__main__':main()
