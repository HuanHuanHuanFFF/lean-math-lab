def valuation(n,p):
    e=0
    while n%p==0:
        n//=p;e+=1
    return e

def small(n,i):
    x=n
    for p in ((2,3) if i==5 else (2,3,5)):
        while x%p==0:x//=p
    if i==5 and x%5==0 and x%25!=0:x//=5
    return n//x

def qig_gap(n,i):
    T=prod(small(n-r,i) for r in range(4))
    return 2**20*(n-1)**6*(n-3)**3-T**6*(3*n*n-12*n+8)

def recover(bound, modulus, tails):
    # Reverse CRT: anchor at the 3-power, not the 2-power used in discovery.
    # The exponents are generated by inequalities p**e < bound.
    a=0
    while 2**(a+1)<bound:a+=1
    b=0
    while 3**(b+1)<bound:b+=1
    lo=set()
    for residue in tails:
        n=residue
        while n<8192:
            if n>=12:lo.add(n)
            n+=modulus
    hi=set()
    for residue,(r,s) in sorted(tails.items(),reverse=True):
        for eb in range(b,0,-1):
            Q=3**eb
            for ea in range(a,0,-1):
                P=2**ea
                n=(s+Q*((r-s)*pow(Q,-1,P)%P))%(P*Q)
                if not (8192<=n<bound and n%modulus==residue):continue
                if valuation(n-r,2)!=ea or valuation(n-s,3)!=eb:continue
                hi.add(n)
    return lo,hi

def prime_certificates(data):
    entries={d['p']:d for d in data}
    require(len(entries)==len(data),'duplicate prime certificate')
    accepted=set()
    for p in sorted(entries):
        d=entries[p]
        require(type(p) is int and p>=2,'invalid prime')
        if p==2:
            accepted.add(2);continue
        fs=d['factorization_p_minus_1'];a=d['a']
        require(len({q for q,e in fs})==len(fs),'duplicate p-1 factor')
        require(all(q in accepted and type(e) is int and e>=1 for q,e in fs),'uncertified p-1 factor')
        require(prod(q**e for q,e in fs)==p-1,'p-1 factorization')
        require(1<a<p and pow(a,p-1,p)==1,'Lucas Fermat condition')
        require(all(gcd(pow(a,(p-1)//q,p)-1,p)==1 for q,e in fs),'Lucas order condition')
        accepted.add(p)
    return accepted

def binomial_v(n,j,p):
    # Factorial floors, independently of the generator's residue tests.
    q=p;ans=0
    while q<=n:
        ans+=n//q-j//q-(n-j)//q;q*=p
    return ans

def terminal_rows(certificate, expected):
    primes=prime_certificates(certificate['prime_certificates'])
    rows=certificate['rows']
    require([r['n'] for r in rows]==expected,'terminal row omission/order')
    num=0
    for row in rows:
        n=row['n'];facts=row['row_factorizations']
        require(len(facts)==5,'missing source row')
        for r,fs in enumerate(facts):
            require(len({p for p,e in fs})==len(fs),'duplicate factor')
            require(all(p in primes and type(e) is int and e>=1 for p,e in fs),'bad source factor')
            require(prod(p**e for p,e in fs)==n-r,'source factorization')
        f0=dict(facts[0]);e5=f0.get(5,0)
        alphas=sorted(2**a*3**b*5**c for a in range(f0.get(2,0)+1)
                      for b in range(f0.get(3,0)+1) for c in range(2 if e5==1 else 1))
        require(alphas==row['alphas'],'alpha template omission')
        fq=[(p,e) for p,e in facts[1] if p not in (2,3) and not (p==5 and e==1)]
        Qs=[p**e for p,e in fq];M=prod(Qs)
        require(M==row['q1'] and M==(n-1)//small(n-1,5),'q1 full-power mismatch')
        if M==1:idents=[0]
        else:
            basis=[(M//Q)*pow(M//Q,-1,Q) for Q in Qs]
            idents=[sum(bit*a for bit,a in zip(bits,basis))%M for bits in product((0,1),repeat=len(Qs))]
        expected_pairs=set()
        for alpha in alphas:
            g=n//alpha;lower=5//g+1;upper=alpha//2
            for z in idents:
                residue=alpha*z%M
                start=residue+((lower-residue+M-1)//M)*M
                for beta in range(start,upper+1,M):
                    if gcd(alpha,beta)==1:expected_pairs.add((alpha,beta))
        supplied={(z['alpha'],z['beta']) for z in row['candidates']}
        require(len(supplied)==len(row['candidates']) and supplied==expected_pairs,'target candidate omission')
        for z in row['candidates']:
            alpha,beta,p,r=z['alpha'],z['beta'],z['p'],z['r']
            g=n//alpha;j=g*beta
            require(5<j<=n//2 and gcd(n,j)==g,'illegal original input')
            require(p in primes and p>=5 and 0<=r<=4,'witness threshold')
            require(p in dict(facts[r]),'source prime is absent')
            vs=binomial_v(n,5,p);vt=binomial_v(n,j,p)
            require(vs==z['source_v'] and vt==z['target_v'] and vs>0 and vt>0,'not a common prime')
            num+=1
    return {'rows':len(rows),'complete_target_candidates':num,'lucas_prime_certificates':len(primes)}

def finite_checks():
    # Product/n entrance: 3*30**6 / 2**19 < 8192, with strict QIG.
    require(3*30**6 < 8192*2**19,'CRT entrance constant')
    six=load('finite.json');B=2*648*125665012224
    require(six['height_exclusive']==B and six['cut']==8192,'H025 height metadata')
    lo,hi=recover(B,1800,{1280:(0,2),1530:(2,0)})
    require(sorted(lo)==six['low_rows'] and sorted(hi)==six['high_rows'],'H025 recovered set')
    require([z['n'] for z in six['rows']]==sorted(lo|hi),'H025 row omission')
    for row in six['rows']:
        gap=qig_gap(row['n'],6)
        require(gap==row['qig_gap'] and gap>0,'H025 QIG rejection')
    five=load('i5_finite.json')
    require(five['bound']==2**206,'i5 absolute height')
    lo5,hi5=recover(2**206,72,{56:(0,2),18:(2,0)})
    all5=sorted(lo5|hi5)
    require(all5==five['rows'],'i5 recovered set')
    terminals=[n for n in all5 if qig_gap(n,5)<=0]
    require(terminals==five['terminals'],'i5 terminal omission')
    tresult=terminal_rows(load('i5_terminals.json'),terminals)
    return {'i6_H025':{'low_rows':len(lo),'high_rows':len(hi),'qig_rows':len(lo|hi)},
            'i5_H02':{'recovered_rows':len(all5),'qig_rows':len(all5)-len(terminals),'terminal_acceptance':tresult}}

def rejection_tests():
    rejected=[]
    def reject(name,fn):
        try:fn()
        except (ValueError,KeyError):rejected.append(name)
        else:raise ValueError('damaged certificate accepted: '+name)
    bad=copy.deepcopy(load('kernel.json')['terms']);bad[0][2]+=1
    reject('polynomial coefficient',lambda:taylor_check(bad,[(1,8,range(2)),(3,4,range(4)),(4,3,range(5)),(5,2,range(6))]))
    neg=[[a,b,-c] for a,b,c in load('kernel.json')['terms']]
    reject('sign reversed',lambda:positive_shift(neg,7))
    cert=load('i5_terminals.json');bad=copy.deepcopy(cert)
    next(d for d in bad['prime_certificates'] if d['p']>2)['a']=1
    reject('primality witness',lambda:prime_certificates(bad['prime_certificates']))
    bad=copy.deepcopy(cert);r=next(r for r in bad['rows'] if r['candidates']);r['candidates'].pop()
    expect=[r['n'] for r in cert['rows']]
    reject('omitted target',lambda:terminal_rows(bad,expect))
    bad=copy.deepcopy(cert);r=next(r for r in bad['rows'] if r['candidates']);r['candidates'][0]['p']=3
    reject('low-prime substitution',lambda:terminal_rows(bad,expect))
    bad=copy.deepcopy(cert);bad['rows'][0]['row_factorizations'][0][0][1]+=1
    reject('full source exponent',lambda:terminal_rows(bad,expect))
    require(small(125,5)==1 and small(125,6)==125 and small(5,5)==5,'endpoint conventions')
    require(binomial_v(150,6,7)==2 and binomial_v(150,7,7)==1,'full 49 regression')
    require(7%7<=150%7 and 7%49>150%49,'radical-loss regression')
    return rejected

