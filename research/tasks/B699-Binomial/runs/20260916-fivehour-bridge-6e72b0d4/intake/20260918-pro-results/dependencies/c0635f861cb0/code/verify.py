def require(test: bool, message: str) -> None:
    if not test: raise ValueError(message)

def load(name: str):
    return json.loads((ROOT/'evidence'/name).read_text())

def terms_check(terms, degree, order):
    require(all(len(t)==3 and all(type(z) is int for z in t) and t[0]>=0 and t[1]>=0 and t[2]!=0 for t in terms),'invalid polynomial term')
    require(len({(a,b) for a,b,c in terms})==len(terms),'duplicate monomial')
    require(max(a+b for a,b,c in terms)==degree,'degree')
    require(min(a+b for a,b,c in terms)==order,'origin order')

def taylor_check(terms, rows):
    count=0
    for r,w,slots in rows:
        for x in slots:
            y=r-x
            for total in range(w):
                for u in range(total+1):
                    v=total-u
                    value=sum(c*comb(a,u)*comb(b,v)*x**(a-u)*y**(b-v)
                              for a,b,c in terms if a>=u and b>=v)
                    require(value==0, f'Taylor failure {r,x,u,v}')
                    count+=1
    return count

def positive_shift(terms, base):
    out=defaultdict(int)
    for a,b,c in terms:
        for u in range(a+1):
            for v in range(b+1):
                out[u,v]+=c*comb(a,u)*comb(b,v)*base**(a+b-u-v)
    require(all(c>=0 for c in out.values()) and out[0,0]>0,'legal-zero/sign failure')
    return sum(c>0 for c in out.values())

def kernels():
    old=load('kernel.json');t=old['terms']
