"""Repair only the synthesized CoverBundle declaration metadata/packaging.

Reads the existing parser cache, never recomputes CRT cells or certificate data,
never invokes Lean, and never overwrites the V2/CI7 source. Actual acceptance
requires the fixed official Linux compiler and independent verifier.
"""
import ast, hashlib, inspect, json, pickle, re, shutil
from datetime import datetime, timezone
from pathlib import Path
from extract import REPO, DECL
from compress_i11 import SCRATCH, add
from pack_consumer import pack, main as pack_main
