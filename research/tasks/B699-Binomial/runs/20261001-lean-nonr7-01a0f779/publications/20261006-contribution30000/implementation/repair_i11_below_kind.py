BASE=Path(__file__).resolve().parent
DEST=BASE/'repairs/20261007-i11-below-kind'
CACHE=SCRATCH/'i11-crt-compact.pickle'

def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def digest(s):return hashlib.sha256(s.encode()).hexdigest()
def source(p):return {'path':str(p.relative_to(REPO).as_posix()),'bytes':p.stat().st_size,'sha256':sha(p)}

def data_block(text,local):
 start=re.search(r'^  (?:let|have) '+re.escape(local)+r'\b',text,re.M)
 if start is None:raise ValueError('missing local data '+local)
 next_step=re.search(r'^  (?:let|have) u\d+\b',text[start.end():],re.M)
 end=start.end()+next_step.start() if next_step else len(text)
 return text[start.start():end].split(':=',1)[1].strip()

def main():
 DEST.mkdir(parents=True,exist_ok=True);(DEST/'analysis').mkdir(exist_ok=True)
 freeze=json.loads((BASE/'v2/FIRST-COMPILE-SNAPSHOT.json').read_text(encoding='utf-8'))
 old=next(x for x in freeze['artifacts'] if Path(x['path']).name=='I11BelowFinalCandidate.lean')
 oldfile=REPO/old['path'];assert sha(oldfile)==old['sha256']
 oldtext=oldfile.read_text(encoding='utf-8')
 oldmap=json.loads((BASE/'v2/analysis/i11-below-local-proof.json').read_text(encoding='utf-8'))
 with CACHE.open('rb') as f:tree,_,_=pickle.load(f)
 fixed=[]
 beforeTexts={k:d['text'] for k,d in tree.decls.items()}
 for d in tree.decls.values():
  if d['line']!=0:continue
  command=DECL.match(d['text'].lstrip())
  if command is None:raise ValueError('unclassified synthesized command '+d['full'])
  actual=command.group(1)
  if d['kind']!=actual:
   fixed.append({'synthesizedFullName':d['full'],'attachedModuleForOrdering':d['module'],'provenance':'new packaging container generated by compress_i11.py FAST/terminal_override; not a pre-existing declaration in Assembly.lean and no new mathematical input','previousKind':d['kind'],'actualKind':actual,'synthesizedTextSHA256':digest(d['text']),'variables':d['variables'],'opens':d['opens']})
   d['kind']=actual
 assert len(fixed)==1 and fixed[0]['synthesizedFullName'].endswith('.CoverBundle') and fixed[0]['actualKind']=='structure',fixed
 assert all(tree.decls[k]['text']==v for k,v in beforeTexts.items())
 namespace='Math.B699.I11OriginalFinal';module=next(p for p in tree.mods if p.endswith('I11OriginalFinal/Final.lean'))
 target=namespace+'.common_i11_below'
 # The source wrapper comes from the current ordinary producer, rather than a
 # second hand-maintained theorem. Its full literal contract is bound below.
 wrappers=[node.value for node in ast.walk(ast.parse(inspect.getsource(pack_main))) if isinstance(node,ast.Constant) and isinstance(node.value,str) and node.value.startswith('theorem common_i11_below ')]
 assert len(wrappers)==1
 add(tree,module,namespace,'common_i11_below',wrappers[0],['B699LargePrimeStructure','Polynomial'],'before')
 selected,edges=tree.slice([target])
 bundle=next(k for k in selected if tree.decls[k]['full'].endswith('.CoverBundle'))
 typeDeps=[]
 for k in sorted(edges[bundle]):
  d=tree.decls[k];typeDeps.append({'original':d['full'],'module':d['module'],'line':d['line'],'kind':d['kind'],'textSHA256':digest(d['text'])})
 assert not tree.decls[bundle]['variables'],'structure cannot capture proof-local variables'
 report=pack(tree,target,DEST/'I11BelowFinalCandidate.lean')
 root=renamed(report,target);p=REPO/report['path']
 text=p.read_text(encoding='utf-8').rstrip()+f"\n\n#check ({root} : {old['literalExpectedType']})\n#print axioms {root}\n"
 p.write_text(text,encoding='utf-8',newline='\n')
 assert p.stat().st_size<=1048576
 assert not re.search(r'^\s+(?:structure|inductive|class|namespace)\b',text,re.M)
 structureName=report['declarationNameMap']['CoverBundle']
 structureLine=next(i for i,s in enumerate(text.splitlines(),1) if s.startswith('structure '+structureName+' where'))
 rootLine=next(i for i,s in enumerate(text.splitlines(),1) if s.startswith('theorem '+report['declarationNameMap']['common_i11_below']))
 assert structureLine<rootLine
 compare=[]
 for original in ['Math.B699.I11TerminalCandidateCoverage.compactBundles','Math.B699.I11TerminalMembership.originalCandidates']:
  before=next(x['localName'] for x in oldmap['localSourceMap'] if x['original']==original)
  after=next(x['localName'] for x in report['localSourceMap'] if x['original']==original)
  olddata=data_block(oldtext,before);newdata=data_block(text,after)
  assert olddata==newdata,'data representation changed: '+original
  item={'original':original,'oldLocal':before,'newLocal':after,'exactEncodedBodyEqual':True,'encodedBodyBytes':len(newdata.encode()),'encodedBodySHA256':digest(newdata)}
  if original.endswith('.compactBundles'):
   item.update(bundles=len(re.findall(r'^\s*⟨\(\d+,\d+\),\[',newdata,re.M)),witnessOccurrences=len(re.findall(r'\.(?:good|special330)\b',newdata)))
   assert item['bundles']==1111 and item['witnessOccurrences']==4041,item
  else:
   item['candidateIntervals']=len(re.findall(r'\(\d+,\d+\)',newdata));assert item['candidateIntervals']==1055,item
  compare.append(item)
 # Bound unchanged existing CRT comparison as separate finite evidence, never
 # promote it to Lean acceptance or rerun its 770427 signed-cell evaluations.
 roundtrip=BASE/'v2/analysis/crt-reencoding-roundtrip.json'
 assert roundtrip.is_file()
 preserved=[]
 for name in ['bundleCheck','bundleCheck_sound','compactBundles_check','compactCandidates_cover']:
  d=next(d for d in tree.decls.values() if d['full']=='Math.B699.I11TerminalCandidateCoverage.'+name)
  assert d['text']==beforeTexts[d['key']]
  preserved.append({'original':d['full'],'textSHA256':digest(d['text'])})
 report['sha256']=sha(p);report['bytes']=p.stat().st_size
 (DEST/'analysis/i11-below-local-proof.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
 data={'status':'exact source data representation comparison only; no new mathematical or kernel acceptance','oldArtifact':source(oldfile),'newArtifact':source(p),'comparisons':compare,'unchangedCheckerProofs':preserved,'allCachedDeclarationBodiesEqualBeforePackaging':True,'CRTRecomputed':False,'wideInventoryRebuilt':False,'existingCRTRoundtrip':source(roundtrip)}
 (DEST/'analysis/data-roundtrip.json').write_text(json.dumps(data,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
 record={'status':'separate static command-placement repair; not selected into CI7; Lean/Std3 pending','timeUTC':datetime.now(timezone.utc).isoformat(),'fixedOldSource':old,'newArtifact':dict(source(p),root=root,literalExpectedType=old['literalExpectedType'],auditsEmbedded=True,compilerStatus='pending',transitiveAxiomStatus='pending',independentVerifierStatus='pending'),'metadataCorrections':fixed,'structureDependencies':typeDeps,'structureAtTopLevelBeforeConsumer':{'name':structureName,'definitionLine':structureLine,'rootLine':rootLine,'proofLocalCaptures':False},'unchangedScope':freeze['fullContract'],'unchangedI11Partition':freeze['i11Split'],'numericData':'1111 bundles/4041 witnesses/1055 original intervals exactly equal to frozen V2; no CRT recomputation','roundtrip':'analysis/data-roundtrip.json','sourcePolicy':'analysis/source-policy.json','precheck':'../I11-STATIC-DEPENDENCY-PRECHECK.json','nativeLeanExecuted':False,'oldSourceAndCI7InputsUntouched':True,'generatorSources':[source(BASE/n) for n in ['extract.py','compress_i11.py','pack_consumer.py','repair_i11_below_kind.py']],'cacheInput':dict(source(CACHE),role='resumable parser cache only, not a proof object; rebuildable from SOURCE-ENTRIES and ordinary producers')}
 (DEST/'FREEZE.json').write_text(json.dumps(record,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
 assert sha(oldfile)==old['sha256']
 print(json.dumps({'bytes':p.stat().st_size,'sha256':sha(p),'root':root,'structureLine':structureLine,'rootLine':rootLine,'bundles':1111,'witnessOccurrences':4041,'candidateIntervals':1055,'oldInputsUnmodified':True,'compile':'pending'},ensure_ascii=False))

if __name__=='__main__':main()
